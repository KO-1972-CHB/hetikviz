// Helper to shuffle options array while preserving correct answer
export function shuffleOptionsWithCorrectIndex(options: string[], correctIndex: number): {
  shuffledOptions: string[];
  newCorrectIndex: number;
} {
  const correctText = options[correctIndex];
  const items = options.slice();

  for (let i = items.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [items[i], items[j]] = [items[j], items[i]];
  }

  const newIndex = items.indexOf(correctText);
  return {
    shuffledOptions: items,
    newCorrectIndex: newIndex >= 0 ? newIndex : 0,
  };
}

// Generate a random 20-question diagnostic test (5 from each level: A1, A2, B1, B2)
export function generateRandomDiagnosticTest(countPerLevel = 5): DiagnosticQuestion[] {
  const levels: CefrLevel[] = ['A1', 'A2', 'B1', 'B2'];
  const selected: DiagnosticQuestion[] = [];

  levels.forEach((lvl) => {
    const pool = DIAGNOSTIC_BANK.filter((q) => q.level === lvl);
    // Shuffle pool
    const shuffledPool = pool.slice().sort(() => 0.5 - Math.random());
    const picked = shuffledPool.slice(0, countPerLevel);

    picked.forEach((q) => {
      const { shuffledOptions, newCorrectIndex } = shuffleOptionsWithCorrectIndex(
        q.options,
        q.correctIndex
      );
      selected.push({
        ...q,
        options: shuffledOptions,
        correctIndex: newCorrectIndex,
      });
    });
  });

  return selected;
}
